// Writes Markers.Generated.cs, the word loops and the "extreme" loops of the sieve.
//
//   dotnet run --file tools/GenMarkers.cs -- <output file> [denseMax] [safe]
//
// Bit i of the sieve is the odd number 2i+1, so the multiples of p are the bits
// h, h+p, h+2p, ... with h = p/2.
//
// Dense (p <= denseMax): p words hold 64*p bits, which is 64 multiples, always at the
// same places. One method per p ORs them in, reading and writing each word once.
//
// Sparse (larger p): eight multiples in a row span exactly p bytes. Which bit gets set
// in each byte depends only on p & 7 and on the bit of the first one, so there are
// 4 * 8 = 32 loops with the eight masks as constants.
using System.Text;

string output = args.Length > 0 ? args[0] : "Markers.Generated.cs";
int denseMax = args.Length > 1 ? int.Parse(args[1]) : 129;
if (denseMax < 3 || denseMax % 2 == 0)
    throw new ArgumentException("denseMax must be odd and at least 3");
// The sparse loops use Unsafe.Add with one range check per call. "safe" writes plain
// span indexing instead, which costs a bounds check per mark and measured about 15% slower.
bool unsafeSparse = !(args.Length > 2 && args[2] == "safe");

var sb = new StringBuilder();
sb.Append($$"""
    // <auto-generated>
    // Generated by tools/GenMarkers.cs (denseMax {{denseMax}}{{(unsafeSparse ? ", unsafe sparse" : "")}}). Do not edit; edit the generator.
    // </auto-generated>
    using System;
    using System.Diagnostics.CodeAnalysis;
    using System.Runtime.CompilerServices;
    using System.Runtime.InteropServices;

    namespace PrimeSieveCS;

    static class Markers
    {
        public const int DenseMax = {{denseMax}};

        // Kept out of the dispatch methods so their hot paths stay small.
        [DoesNotReturn]
        static void ThrowBadFactor(int p) => throw new ArgumentOutOfRangeException(nameof(p), p, null);

        [DoesNotReturn]
        static void ThrowBadRange() => throw new ArgumentOutOfRangeException("limit");

    """);

// Dense: one method for every odd p, prime or not, so nothing here knows the primes.
for (int p = 3; p <= denseMax; p += 2)
{
    int h = (p - 1) / 2;
    sb.Append($$"""

            static void Dense{{p}}(Span<ulong> words, int k0, int k1)
            {
                for (int k = k0; k < k1; k++)
                {
                    Span<ulong> b = words.Slice(k * {{p}}, {{p}});

        """);
    bool declared = false;
    int m = 0;
    while (m < 64)
    {
        int word = (h + m * p) >> 6;
        int first = m;
        while (m < 64 && (h + m * p) >> 6 == word)
            m++;
        if (m - first == 1)
        {
            sb.Append($"            b[{word}] |= 1UL << {(h + first * p) & 63};\n");
            continue;
        }
        sb.Append($"            {(declared ? "" : "ulong ")}v = b[{word}];\n");
        declared = true;
        for (int j = first; j < m; j++)
            sb.Append($"            v |= 1UL << {(h + j * p) & 63};\n");
        sb.Append($"            b[{word}] = v;\n");
    }
    sb.Append("        }\n    }\n");
}

sb.Append("""

        /// <summary>Marks the multiples of <paramref name="p"/> in whole blocks k0..k1-1 of p words each.</summary>
        public static void DenseBlocks(int p, Span<ulong> words, int k0, int k1)
        {
            switch (p)
            {

    """);
for (int p = 3; p <= denseMax; p += 2)
    sb.Append($"            case {p}: Dense{p}(words, k0, k1); break;\n");
sb.Append("""
                default: ThrowBadFactor(p); break;
            }
        }

    """);

// Sparse: one method per (p & 7, bit of the first multiple).
for (int pm = 1; pm < 8; pm += 2)
{
    for (int r = 0; r < 8; r++)
    {
        sb.Append($$"""

                // p & 7 == {{pm}}, first multiple at bit {{r}} of its byte.
                static int Sparse{{pm}}{{r}}(Span<byte> bytes, int idx, int p, int limit)
                {

            """);
        for (int k = 1; k < 8; k++)
            sb.Append($"        int o{k} = ({r} + {k} * p) >> 3;\n");
        sb.Append("""
                    int i = idx >> 3;
                    int end = (limit >> 3) - o7;

            """);
        if (unsafeSparse)
        {
            // The furthest byte touched is i + o7, and the loop keeps that below limit >> 3.
            sb.Append("""
                        if (idx < 0 || (uint)(limit >> 3) > (uint)bytes.Length)
                            ThrowBadRange();
                        ref byte first = ref MemoryMarshal.GetReference(bytes);

                """);
        }
        sb.Append("""
                    for (; i < end; i += p)
                    {

            """);
        if (unsafeSparse)
            sb.Append("            ref byte at = ref Unsafe.Add(ref first, i);\n");
        for (int k = 0; k < 8; k++)
        {
            int bit = (r + k * pm) & 7;
            if (unsafeSparse)
                sb.Append(k == 0 ? $"            at |= 1 << {bit};\n" : $"            Unsafe.Add(ref at, o{k}) |= 1 << {bit};\n");
            else
                sb.Append($"            bytes[{(k == 0 ? "i" : $"i + o{k}")}] |= 1 << {bit};\n");
        }
        sb.Append($$"""
                    }
                    return (i << 3) | {{r}};
                }

            """);
    }
}

sb.Append("""

        /// <summary>
        /// Marks the multiples of <paramref name="p"/> from <paramref name="idx"/>, eight per
        /// iteration, while all eight fall below <paramref name="limit"/>. Returns the next index.
        /// </summary>
        public static int Sparse(int p, Span<byte> bytes, int idx, int limit)
        {
            switch (((p & 7) << 3) | (idx & 7))
            {

    """);
for (int pm = 1; pm < 8; pm += 2)
    for (int r = 0; r < 8; r++)
        sb.Append($"            case {(pm << 3) | r}: return Sparse{pm}{r}(bytes, idx, p, limit);\n");
sb.Append("""
                default: ThrowBadFactor(p); return idx;
            }
        }
    }

    """);

File.WriteAllText(output, sb.ToString());
Console.WriteLine($"wrote {output} (dense 3..{denseMax}{(unsafeSparse ? ", unsafe sparse" : "")})");
