// Command gen writes markers_gen.go, the word loops and the "extreme" loops of the sieve.
//
//	go run ./gen [output file] [denseMax] [checked]
//
// Bit i of the sieve is the odd number 2i+1, so the multiples of p are the bits
// h, h+p, h+2p, ... with h = p/2.
//
// Dense (p <= denseMax): p words hold 64*p bits, which is 64 multiples, always at the
// same places. One function per p ORs them in, reading and writing each word once.
//
// Sparse (larger p): eight multiples in a row span exactly p bytes. Which bit gets set
// in each byte depends only on p & 7 and on the bit of the first one, so there are
// 4 * 8 = 32 loops with the eight masks as constants.
package main

import (
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

func main() {
	output := "markers_gen.go"
	denseMax := 129
	// The sparse loops use unsafe.Add with one range check per call. "checked" writes
	// plain slice indexing instead, which costs a bounds check per mark.
	unsafeSparse := true

	args := os.Args[1:]
	if len(args) > 0 {
		output = args[0]
	}
	if len(args) > 1 {
		n, err := strconv.Atoi(args[1])
		if err != nil || n < 3 || n%2 == 0 {
			fmt.Fprintln(os.Stderr, "denseMax must be odd and at least 3")
			os.Exit(2)
		}
		denseMax = n
	}
	if len(args) > 2 && args[2] == "checked" {
		unsafeSparse = false
	}

	var b strings.Builder
	w := func(text string, a ...any) { fmt.Fprintf(&b, text, a...) }

	w("// Code generated by gen/main.go; DO NOT EDIT.\n\npackage main\n\n")
	if unsafeSparse {
		w("import \"unsafe\"\n\n")
	}
	w("const denseMax = %d\n", denseMax)

	// Dense: one function for every odd p, prime or not, so nothing here knows the primes.
	for p := 3; p <= denseMax; p += 2 {
		h := (p - 1) / 2
		w("\nfunc dense%d(words []uint64, k0, k1 int) {\n", p)
		w("for k := k0; k < k1; k++ {\n")
		w("b := (*[%d]uint64)(words[k*%d:])\n", p, p)
		for m := 0; m < 64; {
			word := (h + m*p) >> 6
			var bits []string
			for m < 64 && (h+m*p)>>6 == word {
				bits = append(bits, fmt.Sprintf("1<<%d", (h+m*p)&63))
				m++
			}
			w("b[%d] |= %s\n", word, strings.Join(bits, " | "))
		}
		w("}\n}\n")
	}

	w("\n// denseBlocks marks the multiples of p in whole blocks k0..k1-1 of p words each.\n")
	w("func denseBlocks(p int, words []uint64, k0, k1 int) {\nswitch p {\n")
	for p := 3; p <= denseMax; p += 2 {
		w("case %d:\ndense%d(words, k0, k1)\n", p, p)
	}
	w("default:\npanic(\"denseBlocks: bad factor\")\n}\n}\n")

	// Sparse: one function per (p & 7, bit of the first multiple).
	for pm := 1; pm < 8; pm += 2 {
		for r := 0; r < 8; r++ {
			w("\n// p & 7 == %d, first multiple at bit %d of its byte.\n", pm, r)
			w("func sparse%d%d(bytes []byte, idx, p, limit int) int {\n", pm, r)
			for k := 1; k < 8; k++ {
				w("o%d := (%d + %d*p) >> 3\n", k, r, k)
			}
			w("i := idx >> 3\nend := limit>>3 - o7\n")
			if unsafeSparse {
				// The furthest byte touched is i + o7, and the loop keeps that below limit >> 3.
				w("if idx < 0 || limit>>3 > len(bytes) {\npanic(\"sparse: bad range\")\n}\n")
				w("first := unsafe.Pointer(unsafe.SliceData(bytes))\n")
			}
			w("for ; i < end; i += p {\n")
			if unsafeSparse {
				w("at := unsafe.Add(first, i)\n")
			}
			for k := 0; k < 8; k++ {
				bit := (r + k*pm) & 7
				switch {
				case unsafeSparse && k == 0:
					w("*(*byte)(at) |= 1 << %d\n", bit)
				case unsafeSparse:
					w("*(*byte)(unsafe.Add(at, o%d)) |= 1 << %d\n", k, bit)
				case k == 0:
					w("bytes[i] |= 1 << %d\n", bit)
				default:
					w("bytes[i+o%d] |= 1 << %d\n", k, bit)
				}
			}
			if r == 0 {
				w("}\nreturn i << 3\n}\n")
			} else {
				w("}\nreturn i<<3 | %d\n}\n", r)
			}
		}
	}

	w("\n// sparse marks the multiples of p from idx, eight per round, while all eight fall\n")
	w("// below limit. It returns the next index.\n")
	w("func sparse(p int, bytes []byte, idx, limit int) int {\nswitch (p&7)<<3 | idx&7 {\n")
	for pm := 1; pm < 8; pm += 2 {
		for r := 0; r < 8; r++ {
			w("case %d:\nreturn sparse%d%d(bytes, idx, p, limit)\n", pm<<3|r, pm, r)
		}
	}
	w("default:\npanic(\"sparse: bad factor\")\n}\n}\n")

	source, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "generated code does not parse:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(output, source, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	mode := "unsafe sparse"
	if !unsafeSparse {
		mode = "checked sparse"
	}
	fmt.Printf("wrote %s (dense 3..%d, %s)\n", output, denseMax, mode)
}
